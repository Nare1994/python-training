"""
Палиндром: строка читается одинаково в обе стороны.
"""


def is_palindrome(s):
    s = s.lower()  # Переводим все буквы в нижний регистр и заменяем пустую строку на пустую строку.
    return s == s[::-1]  # Сравниваем строку с перевёрнутой.


# Проверяем, является ли слово "Anna" палиндромом.
print(is_palindrome("Anna"))
print(is_palindrome("hello"))

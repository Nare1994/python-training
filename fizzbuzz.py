"""
Программа FizzBuzz.

Выводит числа от 1 до 100:
- "FizzBuzz" — если число делится и на 3, и на 5.
- "Fizz" — если число делится на 3.
- "Buzz" — если число делится на 5.
- Иначе — само число.
"""


def fizzbuzz(n):
    # Сначала проверяем делимость на 15 (и на 3, и на 5)
    if n % 15 == 0:
        return "FizzBuzz"
    # Проверяем, делится ли число на 3
    elif n % 3 == 0:
        return "Fizz"
    # Проверяем, делится ли число на 5
    elif n % 5 == 0:
        return "Buzz"
    # Если ни одно условие не подошло — возвращаем число как строку
    return str(n)


if __name__ == "__main__":
    # Проходим по числам от 1 до 100 (включительно)
    for i in range(1, 101):
        # Выводим результат для каждого числа
        print(fizzbuzz(i))
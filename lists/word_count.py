# Задача 1. Подсчёт слов
# Пользователь вводит несколько слов через пробел.
#
# Требуется:
#
# Сохранить все слова в список.
#
# Вывести количество слов.
#
# Вывести самое длинное слово.
#
# Вывести самое короткое слово.


world_counts = input("Пользователь вводит слово: ")

result = world_counts.split()

print(result)                 # Список слов
print(len(result))            # Количество слов
print(max(result, key=len))   # Самое длинное слово
print(min(result, key=len))   # Самое короткое слово

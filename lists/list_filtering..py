# Задача: «Фильтр чисел»
# Условие:
# Пользователь вводит список чисел через пробел (одной строкой).
# Программа должна отфильтровать этот список и
# оставить в нём только чётные положительные числа.
#
# Требования:
#

# Получить от пользователя строку с числами (например, -5 3 8 0 12 -2 7).
#
# Преобразовать строку в список целых чисел.
#
# Создать новый список, в который войдут только числа, которые одновременно:
#
# являются чётными (делятся на 2 без остатка),
#
# являются положительными (больше нуля).
#
# Вывести исходный список и отфильтрованный список.
#
# Если после фильтрации список пуст — вывести сообщение: "Подходящих чисел нет".

#


numbers = list(map(int, input("Введите числа через пробел: ").split()))

filtered = []

for num in numbers:
    if num > 0 and num % 2 == 0:
        filtered.append(num)
print("Исходный список:", numbers)

if filtered:
    print("Отфильтрованный список:", filtered)
else:
    print("Подходящих чисел нет")

# Задача
# Условие: Дан список чисел.
# Требования:
#
# Отсортировать список по возрастанию.
#
# Отсортировать список по убыванию.
#
# Вывести оба результата.
#
# (Дополнительно) Отсортировать по модулю числа
# (например, [-5, 3, -1] → [-1, 3, -5]).


numbers = [5, 12, 33, 55, 73, 101]

# Сортировка по возрастанию
ascending = sorted(numbers)
print("По возрастанию:", ascending)

# Сортировка по убыванию
descending = sorted(numbers, reverse=True)
print("По убыванию:", descending)

# Сортировка по модулю числа
numbers2 = [-5, 3, -1]
by_absolute = sorted(numbers2, key=abs)
print("По модулю:", by_absolute)
